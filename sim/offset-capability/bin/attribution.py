#!/usr/bin/env python3
"""Per-device-group attribution of the offset Monte Carlo sigma (issue #107).

Reuses `offset_probe.py` (request builder, `klt sim` client, extractor,
aggregator, echo check) and the `bench/offset_dc.cir` source/load/sweep
conventions. Measured data only: no limit, no ratification.

How a group is isolated. `klt sim` has no control that enables mismatch per
instance or per device family: `corners.process = "<corner>_mm"` sets the
global `mc_mm_switch=1` for the whole library. The mismatch terms in the
sky130 models are `MC_MM_SWITCH*AGAUSS(0,1,1)*...`, evaluated in subcircuit
scope, so a *bench-level* wrapper subcircuit that declares a local
`.param mc_mm_switch=0` around the PDK device zeroes every mismatch term of
the devices placed inside it (verified: identical to the mismatch-off value,
see records/attribution-20261009.md). The per-group benches in
`bench/attribution/` are generated by `gen` from the committed
`design/netlist/opamp_core.spice`: the devices of the group under test keep
the PDK model name (mismatch on), every other device is rerouted through the
`mmoff_*` wrapper. The design netlist itself is not modified. That the wrapper
is the only difference is checked by `tests/test_attribution.py` (regenerated
benches must equal the committed ones) and by the `none` control (all devices
wrapped, mismatch lib section on: must return the systematic baseline).

Usage:
  attribution.py gen
  attribution.py run --label NAME --base-seed N [--groups pair,mirror,...]
                     [--only group:chunk,...] [--backend NAME] [--dry-run]
  attribution.py summarize [--out PATH]

`run` submits one seeded `monte_carlo` `klt sim` request per (group, chunk),
sequentially, through `offset_probe.run_one` (backend from $KLT_SIM_BACKEND,
`batch` on dispatch hosts). It never launches ngspice itself and never falls
back to a local grid: a failed submit is retried only for fleet-capacity
refusals, and is otherwise recorded as failed. Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import math
import re
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import offset_probe as op  # noqa: E402
from spice_harness import allocate_record_id, write_new  # noqa: E402

EXP = op.EXP
REPO = op.REPO
RECORDS = op.RECORDS
BENCH_DIR = EXP / "bench" / "attribution"
CORE = REPO / "design" / "netlist" / "opamp_core.spice"
BASE_BENCH = EXP / "bench" / "offset_dc.cir"

# group -> (instances with mismatch ON, N per group). Verified against
# design/netlist/opamp_core.spice by `instances()`/test_attribution.
GROUPS = {
    "pair":     (("XM1", "XM2"), 300),    # input pair
    "mirror":   (("XM3", "XM4"), 300),    # PMOS mirror load
    "stage2":   (("XM6", "XM7"), 300),    # second stage (PMOS CS + NMOS sink)
    "bias":     (("XM5", "XMB1"), 300),   # tail source + bias diode
    "passives": (("XRz", "XCc"), 100),    # Rz and Cc (no DC current expected)
    "none":     ((), 4),                  # control: all wrapped -> baseline
}
MODEL_WRAP = {
    "sky130_fd_pr__nfet_01v8": "mmoff_nfet",
    "sky130_fd_pr__pfet_01v8": "mmoff_pfet",
    "sky130_fd_pr__res_high_po_1p41": "mmoff_res",
    "sky130_fd_pr__cap_mim_m3_1": "mmoff_cap",
}
WRAPPERS = """\
* mismatch-off wrappers (issue #107). The local `.param mc_mm_switch=0` shadows
* the library's global switch for everything instantiated inside, so the PDK
* device keeps its nominal (non-random) model while the rest of the deck, and
* the library section, still have mismatch on. Parameter lists mirror the PDK
* subcircuits; `mult` and `m` are passed to the inner device explicitly. (Without the
* explicit `m`, ngspice dropped the X-line multiplier when no un-wrapped device of
* that kind was left in the deck: a 1-2 mV systematic shift, caught by the control.)
.subckt mmoff_nfet d g s b l=1 w=1 nf=1 ad=0 as=0 pd=0 ps=0 nrd=0 nrs=0 sa=0 sb=0 sd=0 mult=1 m=1
.param mc_mm_switch=0
XX d g s b sky130_fd_pr__nfet_01v8 l={l} w={w} nf={nf} ad={ad} as={as} pd={pd} ps={ps} nrd={nrd} nrs={nrs} sa={sa} sb={sb} sd={sd} mult={mult} m={m}
.ends
.subckt mmoff_pfet d g s b l=1 w=1 nf=1 ad=0 as=0 pd=0 ps=0 nrd=0 nrs=0 sa=0 sb=0 sd=0 mult=1 m=1
.param mc_mm_switch=0
XX d g s b sky130_fd_pr__pfet_01v8 l={l} w={w} nf={nf} ad={ad} as={as} pd={pd} ps={ps} nrd={nrd} nrs={nrs} sa={sa} sb={sb} sd={sd} mult={mult} m={m}
.ends
.subckt mmoff_res r0 r1 b l=5 w=1.41 mult=1 m=1
.param mc_mm_switch=0
XX r0 r1 b sky130_fd_pr__res_high_po_1p41 l={l} w={w} mult={mult} m={m}
.ends
.subckt mmoff_cap c0 c1 w=1 l=1 mf=1 m=1
.param mc_mm_switch=0
XX c0 c1 sky130_fd_pr__cap_mim_m3_1 w={w} l={l} mf={mf} m={m}
.ends
"""


def logical_lines(text: str) -> list[str]:
    """Netlist lines with `+` continuations joined (cards kept in file order)."""
    out: list[str] = []
    for ln in text.splitlines():
        if ln.startswith("+") and out:
            out[-1] += " " + ln[1:].strip()
        else:
            out.append(ln.rstrip())
    return out


def instances(core_text: str) -> dict[str, str]:
    """instance name -> PDK model name for every X card in the core netlist."""
    inst = {}
    for ln in logical_lines(core_text):
        if ln.startswith("X"):
            toks = ln.split()
            model = next(t for t in toks if t in MODEL_WRAP)
            inst[toks[0]] = model
    return inst


def gated_netlist(core_text: str, on: tuple[str, ...]) -> str:
    """Core netlist body with every X card not in `on` rerouted through mmoff_*."""
    known = instances(core_text)
    missing = [i for i in on if i not in known]
    if missing:
        raise SystemExit(f"group instance(s) {missing} not in {CORE.name}")
    out = []
    for ln in logical_lines(core_text):
        if ln.startswith("X") and ln.split()[0] not in on:
            toks = ln.split()
            model = known[toks[0]]
            ln = " ".join(MODEL_WRAP[model] if t == model else t for t in toks)
        if ln.strip() == ".end":
            continue
        out.append(ln)
    return "\n".join(out) + "\n"


def bench_text(group: str) -> str:
    on, _n = GROUPS[group]
    base = BASE_BENCH.read_text()
    inc = '.include "../../../design/netlist/opamp_core.spice"'
    if inc not in base:
        raise SystemExit("bench/offset_dc.cir include line not found; regenerate logic needs update")
    on_txt = ", ".join(on) if on else "none (control: every device wrapped)"
    head = (f"* GENERATED by bin/attribution.py gen (issue #107) -- do not edit by hand.\n"
            f"* Offset bench with mismatch enabled only on: {on_txt}.\n"
            f"* Everything else (sources, load, sweep) is bench/offset_dc.cir verbatim; the\n"
            f"* netlist below is design/netlist/opamp_core.spice with every other device\n"
            f"* routed through the mmoff_* wrappers.\n")
    core = gated_netlist(CORE.read_text(), on)
    return head + base.replace(inc, WRAPPERS + "* ---- opamp_core.spice (gated) ----\n" + core)


def bench_path(group: str) -> Path:
    return BENCH_DIR / f"offset_dc_attr_{group}.cir"


def gen() -> int:
    BENCH_DIR.mkdir(parents=True, exist_ok=True)
    for g in GROUPS:
        bench_path(g).write_text(bench_text(g))
        print(bench_path(g).relative_to(REPO))
    return 0


def plan(groups: list[str], base_seed: int, chunk: int = 100) -> list[dict]:
    out = []
    for g in groups:
        n_total = GROUPS[g][1]
        k, done = 0, 0
        while done < n_total:
            n = min(chunk, n_total - done)
            out.append({"group": g, "chunk": k, "seed": base_seed + k, "n": n, "offset": done})
            done += n
            k += 1
    return out


def request_for(group: str, mc: dict) -> dict:
    return op.build_request("offset", True, mc, corner="tt", keep_artifacts=False,
                            netlist=f"../bench/attribution/{bench_path(group).name}")


def run(a) -> int:
    groups = [g.strip() for g in a.groups.split(",") if g.strip()]
    bad = [g for g in groups if g not in GROUPS]
    if bad:
        raise SystemExit(f"unknown group(s) {bad}; choose from {list(GROUPS)}")
    pl = plan(groups, a.base_seed)
    if a.only:
        want = {(x.split(":")[0], int(x.split(":")[1])) for x in a.only.split(",") if x}
        pl = [p for p in pl if (p["group"], p["chunk"]) in want]
    log = []
    for p in pl:
        mc = {"n": p["n"], "seed": p["seed"]}
        req = request_for(p["group"], mc)
        label = f"{a.label}-{p['group']}-c{p['chunk']}"
        if a.dry_run:
            RECORDS.mkdir(exist_ok=True)
            rid = allocate_record_id(RECORDS, f"offset-{label}")
            write_new(RECORDS / f"{rid}.request.json", json.dumps(req, indent=2) + "\n")
            print(rid)
            continue
        for attempt in range(1, a.max_attempts + 1):
            meta = op.run_one(req, label if attempt == 1 else f"{label}-r{attempt}", a.backend, mc=mc,
                              extra={"attribution": a.label, "group": p["group"], "chunk": p["chunk"],
                                     "chunk_seed": p["seed"], "chunk_n": p["n"],
                                     "global_offset": p["offset"], "attempt": attempt,
                                     "mismatch_on": list(GROUPS[p["group"]][0])})
            got = "samples" in meta
            log.append({"record_id": meta["record_id"], "group": p["group"], "chunk": p["chunk"],
                        "attempt": attempt, "exit_code": meta["exit_code"], "got_samples": got,
                        "job_id": (meta.get("remote") or {}).get("job_id")})
            print(json.dumps(log[-1]), flush=True)
            if got or attempt == a.max_attempts:
                break
            time.sleep(a.retry_wait_s if op.is_capacity_error(meta.get("stderr", "")) else 30)
    return 0


# --------------------------------------------------------------- summarize --

def _load_chunks() -> dict[tuple[str, int], dict]:
    """First successful, echo-clean record per (group, chunk), by record id."""
    best: dict[tuple[str, int], dict] = {}
    for sp in sorted(RECORDS.glob("*.summary.json")):
        meta = json.loads(sp.read_text())
        if "attribution" not in meta or "samples" not in meta or meta.get("echo_problems"):
            continue
        key = (meta["group"], meta["chunk"])
        if key in best:
            continue
        payload = json.loads((sp.parent / f"{meta['record_id']}.klt.json").read_text())
        samples = op.extract_samples(payload, "offset")
        probs = op.check_echo(payload, {"n": meta["chunk_n"], "seed": meta["chunk_seed"]}, "tt_mm")
        if probs:
            continue
        best[key] = {**meta, "samples": samples,
                     "job_id": (meta.get("remote") or {}).get("job_id")}
    return best


def campaign_tt_by_index() -> dict[int, float]:
    """Global-sample-index -> Vos from the committed all-devices tt campaign (#85)."""
    finals = sorted(RECORDS.glob("*campaign-offset-mc300-final-*.campaign.json"))
    rep = json.loads(finals[-1].read_text())
    paths = [str(RECORDS / f"{ch['record_id']}.summary.json") for ch in rep["corners"]["tt"]["chunks"]]
    out = {}
    for p in paths:
        meta = json.loads(Path(p).read_text())
        payload = json.loads((Path(p).parent / f"{meta['record_id']}.klt.json").read_text())
        for s in op.extract_samples(payload, "offset"):
            if s.get("ok"):
                out[meta["global_offset"] + s["monte_carlo"]["sample_index"]] = s["vos_v"]
    return out


def pearson(x: list[float], y: list[float]) -> float | None:
    n = len(x)
    if n < 3:
        return None
    mx, my = math.fsum(x) / n, math.fsum(y) / n
    sxy = math.fsum((a - mx) * (b - my) for a, b in zip(x, y))
    sxx = math.fsum((a - mx) ** 2 for a in x)
    syy = math.fsum((b - my) ** 2 for b in y)
    return sxy / math.sqrt(sxx * syy) if sxx > 0 and syy > 0 else None


def summarize(a=None) -> dict:
    chunks = _load_chunks()
    per_group: dict[str, dict] = {}
    by_idx: dict[str, dict[int, float]] = {}
    for g, (_on, n_total) in GROUPS.items():
        got = [chunks[k] for k in sorted(chunks) if k[0] == g]
        if not got:
            continue
        samples = []
        by_idx[g] = {}
        for ch in got:
            for s in ch["samples"]:
                s = dict(s)
                s["global_index"] = ch["global_offset"] + (s.get("monte_carlo") or {}).get("sample_index", 0)
                samples.append(s)
                if s.get("ok"):
                    by_idx[g][s["global_index"]] = s["vos_v"]
        rep = op.aggregate(samples, n_total)
        rep["chunks"] = [{"chunk": c["chunk"], "seed": c["chunk_seed"], "n": c["chunk_n"],
                          "record_id": c["record_id"], "job_id": c["job_id"]} for c in got]
        per_group[g] = rep
    out = {"groups": per_group}
    # Consistency against the all-devices tt campaign on the same per-sample seeds.
    tt = campaign_tt_by_index()
    mm = [g for g in ("pair", "mirror", "stage2", "bias") if g in by_idx]
    if mm and all(per_group[g]["n_ok"] == GROUPS[g][1] for g in mm):
        idx = sorted(set.intersection(*[set(by_idx[g]) for g in mm]) & set(tt))
        # baseline subtraction: each group run carries the same systematic Vos
        base = per_group.get("none", {}).get("mean_v")
        summ = [math.fsum(by_idx[g][i] for g in mm) for i in idx]
        allv = [tt[i] for i in idx]
        var_sum = math.fsum(per_group[g]["sigma_v"] ** 2 for g in mm)
        sig_all = math.sqrt(math.fsum((v - math.fsum(allv) / len(allv)) ** 2 for v in allv) / (len(allv) - 1))
        out["consistency"] = {
            "n_common_samples": len(idx), "baseline_none_mean_v": base,
            "rss_group_sigma_v": math.sqrt(var_sum), "all_devices_tt_sigma_v": sig_all,
            "pearson_sum_of_groups_vs_all_devices": pearson(
                [s - (len(mm) - 1) * (base or 0.0) for s in summ], allv),
            "note": "sum of per-group Vos (minus (k-1) x baseline) vs the same-sample all-devices Vos; "
                    "equal if per-instance draws are independent of gating and the response is additive",
        }
    return out


def fmt_summary(rep: dict) -> str:
    rows = ["| group | ok/requested | mean (mV) | sigma (mV) | min / max (mV) | variance share of RSS |",
            "|---|---|---|---|---|---|"]
    gs = rep["groups"]
    tot = math.fsum(gs[g]["sigma_v"] ** 2 for g in ("pair", "mirror", "stage2", "bias", "passives")
                    if g in gs and gs[g]["sigma_v"] is not None)
    for g, r in gs.items():
        sg = r["sigma_v"]
        share = f"{100 * sg ** 2 / tot:.1f} %" if (sg is not None and g != "none" and tot) else "-"
        f = lambda v: "-" if v is None else f"{v * 1e3:+.3f}"  # noqa: E731
        rows.append(f"| {g} | {r['n_ok']}/{r['n_requested']} | {f(r['mean_v'])} | "
                    f"{'-' if sg is None else f'{sg * 1e3:.3f}'} | {f(r['min_v'])} / {f(r['max_v'])} | {share} |")
    return "\n".join(rows)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("gen")
    r = sub.add_parser("run")
    r.add_argument("--label", required=True)
    r.add_argument("--base-seed", type=int, required=True)
    r.add_argument("--groups", default="none,pair,mirror,stage2,bias,passives")
    r.add_argument("--only")
    r.add_argument("--max-attempts", type=int, default=6)
    r.add_argument("--retry-wait-s", type=int, default=300)
    r.add_argument("--backend")
    r.add_argument("--dry-run", action="store_true")
    s = sub.add_parser("summarize")
    s.add_argument("--out")
    a = ap.parse_args(argv)
    if a.cmd == "gen":
        return gen()
    if a.cmd == "run":
        return run(a)
    rep = summarize(a)
    print(json.dumps(rep, indent=2))
    print(fmt_summary(rep), file=sys.stderr)
    if a.out:
        write_new(Path(a.out), json.dumps(rep, indent=2) + "\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
